#!/usr/bin/env bash
# Turn the PyInstaller one-dir build (dist/LFPlusEditor) into a portable AppImage.
#
#   packaging/linux/make_appimage.sh [VERSION]
#
# VERSION defaults to lfeditor.__version__. Output: dist/LFPlusEditor-<VERSION>-x86_64.AppImage
# Requires: a prior `pyinstaller packaging/lfeditor.spec`, plus `appimagetool` on PATH or
# downloadable (the script fetches it if missing). Run from the repo root.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
cd "$ROOT"

VERSION="${1:-$(python -c 'import lfeditor; print(lfeditor.__version__)')}"
DIST="dist/LFPlusEditor"
[ -d "$DIST" ] || { echo "error: $DIST not found — run pyinstaller first" >&2; exit 1; }

APPDIR="build/LFPlusEditor.AppDir"
rm -rf "$APPDIR"
mkdir -p "$APPDIR/usr/bin"
cp -r "$DIST"/. "$APPDIR/usr/bin/"

# launcher + desktop entry
install -m 0755 packaging/linux/AppRun "$APPDIR/AppRun"
cp packaging/linux/lfeditor.desktop "$APPDIR/lfeditor.desktop"

# icon (generated by make_icons.py); fall back to a 1x1 so appimagetool still succeeds
if [ -f packaging/icons/app.png ]; then
    cp packaging/icons/app.png "$APPDIR/lfeditor.png"
else
    echo "warning: packaging/icons/app.png missing — AppImage will have no icon" >&2
    : > "$APPDIR/lfeditor.png"
fi

# fetch appimagetool if it isn't already available
TOOL="$(command -v appimagetool || true)"
if [ -z "$TOOL" ]; then
    TOOL="build/appimagetool"
    if [ ! -x "$TOOL" ]; then
        echo "downloading appimagetool…"
        curl -fsSL -o "$TOOL" \
          "https://github.com/AppImage/appimagetool/releases/download/continuous/appimagetool-x86_64.AppImage"
        chmod +x "$TOOL"
    fi
fi

OUT="dist/LFPlusEditor-${VERSION}-x86_64.AppImage"
# ARCH is required by appimagetool; --appimage-extract-and-run avoids needing FUSE on CI runners.
ARCH=x86_64 "$TOOL" --appimage-extract-and-run "$APPDIR" "$OUT"
echo "wrote $OUT"
